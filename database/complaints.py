def get_or_create_complaint_draft(
    inspection_id: int,
    user_id: Optional[int] = None,
    username: Optional[str] = None,
    db_path: str = DEFAULT_DB_PATH
) -> Dict[str, Any]:
    """
    Fetches the existing complaint draft for an inspection, or initializes
    a new draft from the authentic inspection record.
    Attaches confirmed location, defect metrics, and official submission guidance.
    """
    init_complaints_db(db_path)
    conn = get_db_connection(db_path)
    cursor = conn.cursor()

    cursor.execute("SELECT * FROM defect_inspections WHERE id = ?;", (inspection_id,))
    insp_row = cursor.fetchone()
    if not insp_row:
        conn.close()
        raise ValueError(f"Inspection #{inspection_id} does not exist.")

    inspection = row_to_dict(insp_row)

    cursor.execute("SELECT * FROM complaint_drafts WHERE inspection_id = ?;", (inspection_id,))
    row = cursor.fetchone()

    unique_ref = f"VG-CMP-{inspection_id:04d}"

    if row:
        draft = row_to_dict(row)
        if not draft.get("submission_reference"):
            cursor.execute("UPDATE complaint_drafts SET submission_reference = ? WHERE id = ?;", (unique_ref, draft["id"]))
            conn.commit()
            draft["submission_reference"] = unique_ref
        conn.close()
    else:
        complaint_type = "building_defect" if (inspection.get("inspection_type") == "home") else "road_distress"
        recipient_agency, subject, complaint_body = generate_default_complaint_content(inspection)

        default_complainant = username if (username and username != "guest") else None

        cursor.execute("""
        INSERT INTO complaint_drafts (
            inspection_id, complaint_type, recipient_agency, subject, complaint_body,
            status, created_by_user_id, created_by_username, complainant_name,
            submission_reference
        ) VALUES (?, ?, ?, ?, ?, 'draft', ?, ?, ?, ?);
        """, (
            inspection_id,
            complaint_type,
            recipient_agency,
            subject,
            complaint_body,
            user_id,
            username,
            default_complainant,
            unique_ref,
        ))
        conn.commit()

        cursor.execute("SELECT * FROM complaint_drafts WHERE inspection_id = ?;", (inspection_id,))
        created_row = cursor.fetchone()
        conn.close()
        if not created_row:
            raise RuntimeError(f"Failed to retrieve created complaint draft for inspection #{inspection_id}")
        draft = row_to_dict(created_row)

    unique_ref = draft.get("submission_reference") or f"VG-CMP-{inspection_id:04d}"
    draft["submission_reference"] = unique_ref
    draft["complaint_id"] = unique_ref
    draft["reference_id"] = unique_ref
    draft["is_official_submission"] = (draft.get("status") == "submitted")
    draft["disclaimer"] = COMPLAINT_DISCLAIMER_TEXT
    draft["inspection_type"] = inspection.get("inspection_type") or "road"
    draft["inspection_defect_type"] = inspection.get("defect_type")
    draft["inspection_defect_count"] = inspection.get("defect_count", 0)
    draft["inspection_confidence"] = inspection.get("confidence")
    draft["inspection_image_name"] = inspection.get("image_name")
    draft["inspection_location"] = ", ".join(
        [p for p in [inspection.get("road_name"), inspection.get("area"), inspection.get("city")] if p]
    ) or "Location not specified"
    draft["inspection_latitude"] = inspection.get("latitude")
    draft["inspection_longitude"] = inspection.get("longitude")
    draft["official_channels"] = get_official_submission_channels(
        domain=draft.get("inspection_type") or "road",
        city=inspection.get("city")
    )

    return draft


def update_complaint_draft(
    inspection_id: int,
    updates: Dict[str, Any],
    user_id: Optional[int] = None,
    username: Optional[str] = None,
    db_path: str = DEFAULT_DB_PATH
) -> Dict[str, Any]:
    """
    Updates an editable complaint draft (recipient_agency, subject, complaint_body, contact details, location).
    Enforces valid lifecycle transitions: 'draft', 'ready_to_submit', 'exported', or 'submitted'.
    'submitted' strictly requires manual citizen submission confirmation.
    """
    init_complaints_db(db_path)
    conn = get_db_connection(db_path)
    cursor = conn.cursor()

    # Ensure draft exists
    cursor.execute("SELECT * FROM complaint_drafts WHERE inspection_id = ?;", (inspection_id,))
    row = cursor.fetchone()
    if not row:
        conn.close()
        get_or_create_complaint_draft(inspection_id, user_id=user_id, username=username, db_path=db_path)
        conn = get_db_connection(db_path)
        cursor = conn.cursor()

    fields = []
    params = []

    # 1. Recipient Agency Validation
    if "recipient_agency" in updates:
        val = str(updates["recipient_agency"]).strip()
        if not val:
            conn.close()
            raise ValueError("Recipient Agency / Authority is required and cannot be empty.")
        fields.append("recipient_agency = ?")
        params.append(val[:200])

    # 2. Subject Line Validation
    if "subject" in updates:
        val = str(updates["subject"]).strip()
        if not val:
            conn.close()
            raise ValueError("Subject line is required and cannot be empty.")
        fields.append("subject = ?")
        params.append(val[:300])

    # 3. Complaint Body Validation & Mandatory Disclaimer Enforcement
    if "complaint_body" in updates:
        body = str(updates["complaint_body"]).strip()
        if not body:
            conn.close()
            raise ValueError("Complaint body is required and cannot be empty.")
        if "DISCLAIMER & LEGAL NOTICE" not in body:
            body = body + "\n\n" + COMPLAINT_DISCLAIMER_TEXT
        fields.append("complaint_body = ?")
        params.append(body)

    # 4. Complainant Name & Contact Info
    if "complainant_name" in updates:
        c_name = str(updates["complainant_name"]).strip() if updates.get("complainant_name") is not None else ""
        fields.append("complainant_name = ?")
        params.append(c_name[:150] if c_name else None)

    if "complainant_contact" in updates:
        c_contact = str(updates["complainant_contact"]).strip() if updates.get("complainant_contact") is not None else ""
        fields.append("complainant_contact = ?")
        params.append(c_contact[:200] if c_contact else None)

    # 5. Location update (synchronize back to defect_inspections if edited)
    if "location_address" in updates and str(updates["location_address"]).strip():
        new_loc = str(updates["location_address"]).strip()
        cursor.execute("UPDATE defect_inspections SET road_name = ? WHERE id = ?;", (new_loc[:200], inspection_id))

    # 6. Status and Submission Lifecycle Handling
    if "status" in updates:
        st = str(updates["status"]).strip().lower()
        if st in ("draft", "ready_to_submit", "exported"):
            fields.append("status = ?")
            params.append(st)
        elif st == "submitted":
            # Strict submission integrity guardrail:
            # Requires explicit manual submission confirmation flag or details
            is_manual = updates.get("manual_submission") is True or updates.get("submission_confirmed") is True
            channel = str(updates.get("submission_channel") or "").strip()
            ref_num = str(updates.get("submission_reference") or "").strip()

            if not is_manual and not channel:
                conn.close()
                raise ValueError(
                    "Cannot mark draft as 'submitted'. VisionGuard AI does not perform official filing. "
                    "The user must manually submit the draft to the appropriate authority."
                )

            fields.append("status = ?")
            params.append("submitted")
            fields.append("submission_channel = ?")
            params.append(channel[:150] or "Manual Citizen Grievance Submission")
            fields.append("submission_reference = ?")
            params.append(ref_num[:150] or "Self-Reported")
            fields.append("submitted_at = CURRENT_TIMESTAMP")
        else:
            conn.close()
            raise ValueError(f"Invalid complaint status: '{st}'. Allowed states are 'draft', 'ready_to_submit', 'exported', or 'submitted'.")

    # If manual submission confirmation is sent without explicit status key
    elif updates.get("manual_submission") is True or updates.get("submission_confirmed") is True:
        channel = str(updates.get("submission_channel") or "").strip()
        ref_num = str(updates.get("submission_reference") or "").strip()
        fields.append("status = ?")
        params.append("submitted")
        fields.append("submission_channel = ?")
        params.append(channel[:150] or "Manual Citizen Grievance Submission")
        fields.append("submission_reference = ?")
        params.append(ref_num[:150] or "Self-Reported")
        fields.append("submitted_at = CURRENT_TIMESTAMP")

    fields.append("updated_at = CURRENT_TIMESTAMP")

    if not fields:
        conn.close()
        return get_or_create_complaint_draft(inspection_id, db_path=db_path)

    params.append(inspection_id)
    sql = f"UPDATE complaint_drafts SET {', '.join(fields)} WHERE inspection_id = ?;"
    cursor.execute(sql, tuple(params))
    conn.commit()
    conn.close()

    return get_or_create_complaint_draft(inspection_id, db_path=db_path)


