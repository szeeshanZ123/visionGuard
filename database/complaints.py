COMPLAINT_DISCLAIMER_TEXT = (
    "DISCLAIMER & LEGAL NOTICE: This document is an unsubmitted civic complaint draft generated by "
    "VisionGuard AI for citizen and inspector assistance. VisionGuard AI has NOT submitted this complaint "
    "to any municipal corporation, highway authority, building safety department, or legal entity. "
    "To initiate official remediation, the user must review, verify, and manually submit this draft through "
    "the appropriate governmental grievance portal or official administrative channel."
)


def init_complaints_db(db_path: str = DEFAULT_DB_PATH) -> None:
    """Initializes the complaint_drafts table in SQLite and performs backward-compatible schema migrations."""
    init_db(db_path)
    if is_postgres_backend(db_path):
        return

    conn = get_db_connection(db_path)
    cursor = conn.cursor()

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS complaint_drafts (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        inspection_id INTEGER NOT NULL UNIQUE,
        complaint_type TEXT NOT NULL DEFAULT 'road_distress',
        recipient_agency TEXT NOT NULL,
        subject TEXT NOT NULL,
        complaint_body TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'draft',
        created_by_user_id INTEGER,
        created_by_username TEXT,
        complainant_name TEXT,
        complainant_contact TEXT,
        submission_channel TEXT,
        submission_reference TEXT,
        submitted_at TIMESTAMP,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (inspection_id) REFERENCES defect_inspections(id) ON DELETE CASCADE
    );
    """)

    cursor.execute("CREATE INDEX IF NOT EXISTS idx_complaint_drafts_insp ON complaint_drafts(inspection_id);")

    # Schema migration: check for missing columns if table already existed
    cursor.execute("PRAGMA table_info(complaint_drafts);")
    existing_cols = {col[1] for col in cursor.fetchall()}
    new_cols = [
        ("complainant_name", "TEXT"),
        ("complainant_contact", "TEXT"),
        ("submission_channel", "TEXT"),
        ("submission_reference", "TEXT"),
        ("submitted_at", "TIMESTAMP"),
    ]
    for col_name, col_type in new_cols:
        if col_name not in existing_cols:
            cursor.execute(f"ALTER TABLE complaint_drafts ADD COLUMN {col_name} {col_type};")

    conn.commit()
    conn.close()


