def format_defect_classification(raw_type: Any, domain: str = "road") -> str:
    """Formats defect strings to canonical, human-readable civil engineering categories based on inspection domain."""
    if not raw_type:
        return "Infrastructure Distress"
    clean_k = str(raw_type).strip().lower().replace(" ", "_")
    dom = (domain or "road").lower().strip()

    if dom in ("home", "building"):
        if clean_k in BUILDING_DEFECT_MAP:
            return BUILDING_DEFECT_MAP[clean_k]
        if "," in str(raw_type):
            parts = [format_defect_classification(p.strip(), domain) for p in str(raw_type).split(",")]
            return ", ".join(parts)
        if "crack" in clean_k:
            return "Wall Crack"
        if "deterioration" in clean_k or "spalling" in clean_k:
            return "Surface Spalling"
        if clean_k in ROAD_DEFECT_MAP:
            return ROAD_DEFECT_MAP[clean_k]
    else:
        if clean_k in ROAD_DEFECT_MAP:
            return ROAD_DEFECT_MAP[clean_k]
        if "," in str(raw_type):
            parts = [format_defect_classification(p.strip(), domain) for p in str(raw_type).split(",")]
            return ", ".join(parts)
        if clean_k in BUILDING_DEFECT_MAP:
            return BUILDING_DEFECT_MAP[clean_k]

    return str(raw_type).replace("_", " ").title()


def sanitize_pdf_value(val: Any, default: str = "Not provided") -> str:
    """Sanitizes text fields for PDF output, replacing placeholders like '[Please enter...]' with 'Not provided'."""
    if val is None:
        return default
    s = str(val).strip()
    if not s:
        return default
    if s.startswith("[") and s.endswith("]") and "please" in s.lower():
        return default
    if s.lower() in ("none", "null", "n/a", "not specified"):
        return default
    return s


def resolve_image_path(path_str: Optional[str]) -> Optional[str]:
    """Resolves relative image paths against the application root directory."""
    if not path_str or not str(path_str).strip():
        return None
    p = str(path_str).strip()
    if os.path.isabs(p) and os.path.exists(p):
        return p
    base_dir = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
    cand = os.path.join(base_dir, p)
    if os.path.exists(cand):
        return cand
    cand_norm = os.path.join(base_dir, p.replace("\\", "/"))
    if os.path.exists(cand_norm):
        return cand_norm
    return None


def create_proportional_rl_image(img_path_or_bytes: Any, max_width: float = 255.0, max_height: float = 170.0) -> Optional[RLImage]:
    """Scales an image to fit inside max dimensions while strictly preserving its original aspect ratio."""
    try:
        if not img_path_or_bytes:
            return None
        if isinstance(img_path_or_bytes, bytes):
            stream = io.BytesIO(img_path_or_bytes)
            pil_img = PILImage.open(stream)
            w, h = pil_img.size
            stream.seek(0)
            src = stream
        elif isinstance(img_path_or_bytes, str) and os.path.exists(img_path_or_bytes):
            pil_img = PILImage.open(img_path_or_bytes)
            w, h = pil_img.size
            src = img_path_or_bytes
        else:
            return None

        aspect = w / float(h)
        if aspect > (max_width / float(max_height)):
            new_w = max_width
            new_h = max_width / aspect
        else:
            new_h = max_height
            new_w = max_height * aspect
        return RLImage(src, width=new_w, height=new_h)
    except Exception as e:
        logger.warning("Failed to render proportional image for PDF: %s", e)
        return None


class NumberedCanvas(canvas.Canvas):
    """ReportLab Canvas that computes dynamic two-pass total page count and adds running header/footer."""
    doc_ref = "VG-REPORT"
    insp_id = ""
    doc_date = ""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, page_count):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(colors.HexColor("#64748b"))

        # Running header for page 2 onwards
        if self._pageNumber > 1:
            self.drawString(36, 762, f"VisionGuard AI — Infrastructure Grievance Notice | Ref: #{self.doc_ref} (Insp #{self.insp_id})")
            self.setStrokeColor(colors.HexColor("#cbd5e1"))
            self.setLineWidth(0.5)
            self.line(36, 756, 576, 756)

        # Running footer for all pages
        self.setStrokeColor(colors.HexColor("#e2e8f0"))
        self.setLineWidth(0.5)
        self.line(36, 42, 576, 42)

        footer_left = f"Record #{self.insp_id} | Date: {self.doc_date}"
        footer_center = "MUNICIPAL GRIEVANCE & STRUCTURAL INSPECTION NOTICE"
        footer_right = f"Page {self._pageNumber} of {page_count}"

        self.drawString(36, 30, footer_left)
        self.drawCentredString(306, 30, footer_center)
        self.drawRightString(576, 30, footer_right)
        self.restoreState()



def init_complaints_db(db_path: str = DEFAULT_DB_PATH) -> None:
    """Initializes the complaint_drafts table in SQLite and performs backward-compatible schema migrations."""
    init_db(db_path)
    if is_postgres_backend(db_path):
        return

    conn = get_db_connection(db_path)
    cursor = conn.cursor()

    cursor.execute("""
    CREATE TABLE IF NOT EXISTS complaint_drafts (
        id INTEGER PRIMARY KEY AUTOINCREMENT,
        inspection_id INTEGER NOT NULL UNIQUE,
        complaint_type TEXT NOT NULL DEFAULT 'road_distress',
        recipient_agency TEXT NOT NULL,
        subject TEXT NOT NULL,
        complaint_body TEXT NOT NULL,
        status TEXT NOT NULL DEFAULT 'draft',
        created_by_user_id INTEGER,
        created_by_username TEXT,
        complainant_name TEXT,
        complainant_contact TEXT,
        submission_channel TEXT,
        submission_reference TEXT,
        submitted_at TIMESTAMP,
        created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
        FOREIGN KEY (inspection_id) REFERENCES defect_inspections(id) ON DELETE CASCADE
    );
    """)

    cursor.execute("CREATE INDEX IF NOT EXISTS idx_complaint_drafts_insp ON complaint_drafts(inspection_id);")

    # Schema migration: check for missing columns if table already existed
    cursor.execute("PRAGMA table_info(complaint_drafts);")
    existing_cols = {col[1] for col in cursor.fetchall()}
    new_cols = [
        ("complainant_name", "TEXT"),
        ("complainant_contact", "TEXT"),
        ("submission_channel", "TEXT"),
        ("submission_reference", "TEXT"),
        ("submitted_at", "TIMESTAMP"),
    ]
    for col_name, col_type in new_cols:
        if col_name not in existing_cols:
            cursor.execute(f"ALTER TABLE complaint_drafts ADD COLUMN {col_name} {col_type};")

    conn.commit()
    conn.close()


