    domain = (inspection.get("inspection_type") or "road").lower().strip()
    road_name = inspection.get("road_name") or ("Specified Road Corridor" if domain == "road" else "Specified Property Address")
    area = inspection.get("area") or ""
    city = inspection.get("city") or ""
    lat = inspection.get("latitude")
    lon = inspection.get("longitude")
    defect_type = inspection.get("defect_type") or "Infrastructure Distress"
    defect_count = inspection.get("defect_count", 0)
